buzzer = PWM(Pin(BUZZER_PIN))
buzzer.duty_u16(0)


def duration_for(divider):
    whole_note_ms = (60000 * 4) // TEMPO
    duration_ms = whole_note_ms // abs(divider)
    return (duration_ms * 3) // 2 if divider < 0 else duration_ms


def play_note(frequency, duration_ms):
    sounding_ms = (duration_ms * 9) // 10
    if frequency:
        buzzer.freq(frequency)
        buzzer.duty_u16(VOLUME)
    time.sleep_ms(sounding_ms)
    buzzer.duty_u16(0)
    time.sleep_ms(duration_ms - sounding_ms)


def play_song():
    for index in range(0, len(MELODY), 2):
        play_note(MELODY[index], duration_for(MELODY[index + 1]))


try:
    print("Playing GPIO 14 piezo test")
    play_song()
    print("Finished")
finally:
    buzzer.duty_u16(0)
    buzzer.deinit() 
